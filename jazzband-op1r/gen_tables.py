# Generates plugins/jazzband/jb_tables.h: every pitch / decay constant the plugin needs, so the
# OP-1 side never touches floating point (the Blackfin has no FPU).
import math
SR, BLK = 44100, 64
def inc(f): return min(0xFFFFFFFF, int(round(f * 2**32 / SR)))
def blkdec(t60): return max(0, min(32767, int(round(32768 * 0.001 ** (BLK / (t60 * SR))))))
def mtof(n): return 440.0 * 2 ** ((n - 69) / 12)
L = ["/* generated by gen_tables.py - do not edit */", "#ifndef JB_TABLES_H", "#define JB_TABLES_H", "#include <stdint.h>"]
def arr(ctype, name, vals, per=8):
    L.append(f"static const {ctype} {name}[{len(vals)}] = {{")
    for i in range(0, len(vals), per): L.append("    " + ", ".join(str(v) for v in vals[i:i+per]) + ",")
    L.append("};")
arr("uint32_t", "JB_INC", [inc(mtof(n)) for n in range(128)], 6)
pinc, pdec = [], []
for n in range(128):
    f = mtof(n); tb = 3.2 * 2 ** (-(n - 60) / 24)
    for k in range(1, 5):
        fk = f * k * math.sqrt(1 + 0.00035 * k * k)
        pinc.append(inc(fk) if fk < 9000 else 0)
        pdec.append(blkdec(tb / (1 + 0.45 * (k - 1))))
arr("uint32_t", "JB_PIANO_INC", pinc, 4)
arr("uint16_t", "JB_PIANO_DEC", pdec, 8)
arr("int16_t", "JB_PIANO_AMP", [int(round(32767 * k ** -1.3)) for k in range(1, 5)])
# guitar: Karplus-Strong loop length and fractional allpass coefficient (Q15), tuned for loop delay N - 0.5 + d
ksn, ksa = [], []
for n in range(128):
    P = SR / mtof(n) + 0.5; N = int(math.floor(P - 0.1)); d = P - N
    N = max(2, min(1023, N)); ksn.append(N); ksa.append(int(round(32767 * (1 - d) / (1 + d))))
arr("int16_t", "JB_KS_N", ksn); arr("int16_t", "JB_KS_AP", ksa)
consts = {
  "JB_DEC_KICK": blkdec(0.35), "JB_DEC_KICKP": blkdec(0.05), "JB_DEC_SNARE": blkdec(0.2), "JB_DEC_SNTONE": blkdec(0.06),
  "JB_DEC_RIDE": blkdec(1.4), "JB_DEC_HAT": blkdec(0.07), "JB_DEC_CRASH": blkdec(2.8), "JB_DEC_STICK": blkdec(0.03),
  "JB_DEC_BASS0": blkdec(1.8), "JB_DEC_BASS1": blkdec(0.9), "JB_DEC_BASS2": blkdec(0.45),
  "JB_REL_PIANO": blkdec(0.25), "JB_REL_BASS": blkdec(0.07), "JB_REL_GTR": blkdec(0.05), "JB_REL_STOP": blkdec(0.15),
  "JB_INC_48HZ": inc(48), "JB_INC_75HZ": inc(75), "JB_INC_SNARE": inc(185), "JB_INC_PING": inc(2950),
  "JB_HP82": int(round(32767 * 0.82)), "JB_HP80": int(round(32767 * 0.8)), "JB_HP60": int(round(32767 * 0.6)),
  "JB_SVF_F105": int(round(32768 * 2 * math.sin(math.pi * 105 / SR))), "JB_SVF_F240": int(round(32768 * 2 * math.sin(math.pi * 240 / SR))),
  "JB_SVF_Q105": int(round(32768 / 2.5)), "JB_SVF_Q240": int(round(32768 / 2.2)),
  "JB_LP3200": int(round(32768 * (1 - math.exp(-2 * math.pi * 3200 / SR)))),
  "JB_STRUM": int(round(0.007 * SR)),
  "JB_DEC_EP": blkdec(2.5), "JB_DEC_EPI": blkdec(0.9), "JB_DEC_FMB": blkdec(1.0), "JB_DEC_FMBI": blkdec(0.18),
  "JB_REL_SMP": blkdec(0.12),
}
for k, v in consts.items(): L.append(f"#define {k} {v}")
arr("uint32_t", "JB_METAL_RIDE", [inc(f * 1.6) for f in (205.3, 304.4, 369.6, 522.7, 540.0, 800.0)], 6)
arr("uint32_t", "JB_METAL_HAT", [inc(f * 2.1) for f in (205.3, 304.4, 369.6, 522.7, 540.0, 800.0)], 6)
# sample playback: pitch ratio for -48..+48 semitones, Q16
arr("uint32_t", "JB_RATIO", [int(round(2 ** (d / 12) * 65536)) for d in range(-48, 49)], 8)
L.append("#endif")
open("plugins/jazzband/jb_tables.h", "w").write("\n".join(L) + "\n")
print("ok", len(L), "lines")
