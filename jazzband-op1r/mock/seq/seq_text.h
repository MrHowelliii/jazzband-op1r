typedef struct { int32_t x0, y0, x1, y1, w; uint32_t rgba; } host_line_t;
static host_line_t host_line_log[4096];
static void sq_line(void *r, int32_t x0, int32_t y0, int32_t x1, int32_t y1, int32_t w, const uint8_t *c)
{
    (void)r;
    extern int host_lines_n;
    if (host_lines_n < 4096) {
        host_line_t *l = &host_line_log[host_lines_n];
        l->x0 = x0; l->y0 = y0; l->w = w; l->x1 = x1; l->y1 = y1;
        l->rgba = (uint32_t)c[0] << 24 | (uint32_t)c[1] << 16 | (uint32_t)c[2] << 8 | c[3];
    }
    host_lines_n++;
}
