/* glyphs drawn from the stroke font data (op1r seq_text.h, GPL-3.0-or-later, ultralazr), for the host preview */
static int host_missing_glyphs;
static int32_t sq_text(void *r, int32_t x, int32_t y, int32_t s, const char *t, int32_t w, const uint8_t *c)
{
    for (; *t; t++) {
        int found = 0;
        for (unsigned k = 0; k < sizeof sq_fc - 1; k++) if (sq_fc[k] == *t) {
            const uint8_t *g = sq_seg + 2 * sq_fo[k];
            for (int j = 0; j < sq_fn[k]; j++, g += 2)
                sq_line(r, x + (g[0] >> 4) * s, y + (g[0] & 15) * s, x + (g[1] >> 4) * s, y + (g[1] & 15) * s, w, c);
            found = 1; break;
        }
        if (!found && *t != ' ') host_missing_glyphs++;
        x += (*t == '1' || *t == '.' ? 4 : 6) * s;
    }
    return x;
}
static char *sq_cat(char *p, const char *s) { while (*s) *p++ = *s++; *p = 0; return p; }
static char *sq_num(char *p, uint32_t v, int digits)
{
    char t[10]; int n = 0;
    do { t[n++] = (char)('0' + v % 10); v /= 10; } while (v);
    while (n < digits) t[n++] = '0';
    while (n) *p++ = t[--n];
    *p = 0; return p;
}
