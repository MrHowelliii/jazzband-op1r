#!/usr/bin/env python3
"""Turn a compiled jbsongs.op1p into the companion's template (companion-core.js, between the SONGS_TEMPLATE markers).

    python3 make_songs_template.py <jbsongs.op1p> <companion-core.js>

The template is the file with the empty songbook area cut out (prefix + suffix, base64), and the offsets of the fields
the companion fills. Checks: header, entry magic, no relocation inside the filled area, trailer CRC."""
import base64, binascii, struct, sys
op1p, core = sys.argv[1], sys.argv[2]
f = open(op1p, 'rb').read()
tmagic, bin_off, bin_len, crc = struct.unpack_from('<4I', f, len(f) - 16)
assert tmagic == 0x5431504F and bin_off + bin_len == len(f) - 16 and binascii.crc32(f[bin_off:bin_off + bin_len]) == crc
magic, fmt, api, kind = struct.unpack_from('<4I', f, bin_off)
name = f[bin_off + 16:bin_off + 32].split(b'\0')[0].decode()
image_size, bss_size, entry_off, screen_off = struct.unpack_from('<4I', f, bin_off + 32)
n_relocs, n_imports = struct.unpack_from('<2I', f, bin_off + 68)
assert magic == 0x5031504F and kind == 1 and name == 'jbsongs'
img = bin_off + 76
e = img + entry_off
assert struct.unpack_from('<2I', f, e + 16) == (0x534A424A, 0x31474E4F), 'entry magic'
fields = e + 24                                  # len, sum, count, text
text, MAX = fields + 12, 65536
assert text + MAX <= img + image_size and not any(f[fields:text + MAX])
r0 = img + image_size
for i in range(n_relocs):
    off, typ, target, addend = struct.unpack_from('<IIIi', f, r0 + 16 * i)
    assert not (fields - img <= off < text - img + MAX), f'relocation {i} inside the songbook area'
tpl = {'prefix': base64.b64encode(f[:text]).decode(), 'gap': MAX, 'suffix': base64.b64encode(f[text + MAX:]).decode(),
       'fields': fields, 'text': text, 'max': MAX, 'binOff': bin_off}
js = ('  /* SONGS_TEMPLATE begin: generated by make_songs_template.py from a compiled jbsongs.op1p; do not edit */\n'
      f'  const SONGS_TEMPLATE = {{ prefix: \'{tpl["prefix"]}\',\n    gap: {MAX}, fields: {fields}, text: {text}, binOff: {bin_off},\n'
      f'    suffix: \'{tpl["suffix"]}\' }};\n  /* SONGS_TEMPLATE end */\n')
src = open(core).read()
a, b = src.find('  /* SONGS_TEMPLATE begin'), src.find('  /* SONGS_TEMPLATE end */\n')
if a < 0: raise SystemExit('no SONGS_TEMPLATE markers in ' + core)
src = src[:a] + js + src[b + len('  /* SONGS_TEMPLATE end */\n'):]
open(core, 'w').write(src)
print(f'{core}: template {len(f)} B file, {len(tpl["prefix"]) + len(tpl["suffix"])} B base64, songbook at {text}, {n_relocs} relocs checked')
